-- MEAL_REQUESTS: allow STATUS='DELETED' and record who/when
ALTER TABLE MEAL_REQUESTS ADD (DELETED_BY NUMBER, DELETED_AT TIMESTAMP);
/
ALTER TABLE MEAL_REQUESTS DROP CONSTRAINT CK_MEAL_STATUS;
/
ALTER TABLE MEAL_REQUESTS ADD CONSTRAINT CK_MEAL_STATUS
  CHECK (STATUS IN ('SUBMITTED','LOCKED','CANCELLED','OVERRIDDEN','DELETED'));
/
CREATE INDEX IX_MEAL_REQ_DEL ON MEAL_REQUESTS(DELETED_AT);
/

-- CHAT_MESSAGES: persistent group chat history
CREATE TABLE CHAT_MESSAGES (
  MESSAGE_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SENDER_ID    NUMBER NOT NULL REFERENCES USERS(USER_ID),
  SENDER_NAME  VARCHAR2(120) NOT NULL,
  BODY         VARCHAR2(2000),
  IMAGE_FILE_ID NUMBER REFERENCES UPLOADED_FILES(FILE_ID),
  CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
/
CREATE INDEX IX_CHAT_MSG_CREATED ON CHAT_MESSAGES(CREATED_AT);
/

-- POLLS
CREATE TABLE POLLS (
  POLL_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  QUESTION     VARCHAR2(500) NOT NULL,
  STATUS       VARCHAR2(15) DEFAULT 'OPEN' NOT NULL,
  CREATED_BY   NUMBER NOT NULL REFERENCES USERS(USER_ID),
  CLOSES_AT    TIMESTAMP,
  CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CLOSED_AT    TIMESTAMP,
  CONSTRAINT CK_POLL_STATUS CHECK (STATUS IN ('OPEN','CLOSED','DELETED'))
);
/
CREATE TABLE POLL_OPTIONS (
  OPTION_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  POLL_ID      NUMBER NOT NULL REFERENCES POLLS(POLL_ID) ON DELETE CASCADE,
  OPTION_TEXT  VARCHAR2(300) NOT NULL,
  SORT_ORDER   NUMBER(5) DEFAULT 0 NOT NULL
);
/
CREATE INDEX IX_POLL_OPT_POLL ON POLL_OPTIONS(POLL_ID);
/
CREATE TABLE POLL_VOTES (
  VOTE_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  POLL_ID      NUMBER NOT NULL REFERENCES POLLS(POLL_ID),
  USER_ID      NUMBER NOT NULL REFERENCES USERS(USER_ID),
  OPTION_ID    NUMBER NOT NULL REFERENCES POLL_OPTIONS(OPTION_ID),
  CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_POLL_VOTE UNIQUE (POLL_ID, USER_ID)
);
/
CREATE INDEX IX_POLL_VOTE_POLL ON POLL_VOTES(POLL_ID);
/
