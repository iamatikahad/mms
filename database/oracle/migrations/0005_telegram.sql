-- 0005_telegram.sql — Telegram notification queue + history (Oracle 12c compatible)

CREATE TABLE TELEGRAM_NOTIFICATIONS (
  NOTIF_ID       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  DEDUPE_KEY     VARCHAR2(120) NOT NULL,
  N_TYPE         VARCHAR2(30)  NOT NULL,          -- NEW_REQUEST/UPDATE/CANCEL/ADMIN_OVERRIDE/CUTOFF_SUMMARY/TEST
  MEMBER_ID      NUMBER,
  MEMBER_NAME    VARCHAR2(200),
  MESSAGE_PREVIEW VARCHAR2(1000),                  -- safe summary, never the bot token
  PAYLOAD        CLOB,                             -- full text to send (no secrets inside)
  STATUS         VARCHAR2(12)  DEFAULT 'PENDING' NOT NULL,  -- PENDING/SENT/FAILED
  ATTEMPTS       NUMBER       DEFAULT 0 NOT NULL,
  LAST_ERROR     VARCHAR2(500),
  HTTP_CODE      NUMBER,
  SENT_AT        TIMESTAMP,
  CREATED_AT     TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT     TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_TG_DEDUPE UNIQUE (DEDUPE_KEY)
);

CREATE INDEX IX_TG_STATUS ON TELEGRAM_NOTIFICATIONS (STATUS, CREATED_AT);
CREATE INDEX IX_TG_MEMBER ON TELEGRAM_NOTIFICATIONS (MEMBER_ID, CREATED_AT);
