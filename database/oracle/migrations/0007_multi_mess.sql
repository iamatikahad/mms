-- ---------- 1. MESS_LOCATIONS ----------
CREATE TABLE MESS_LOCATIONS (
  MESS_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  MESS_NAME       VARCHAR2(200) NOT NULL,
  MESS_CODE       VARCHAR2(50)  NOT NULL,
  ADDRESS         VARCHAR2(500),
  CONTACT_NUMBER  VARCHAR2(50),
  STATUS          VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT      TIMESTAMP
);
CREATE UNIQUE INDEX UX_MESS_LOCATIONS_CODE ON MESS_LOCATIONS(MESS_CODE);

-- ---------- 2. MESS_USER_ACCESS (which user can operate which mess) ----------
CREATE TABLE MESS_USER_ACCESS (
  ACCESS_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  MESS_ID      NUMBER NOT NULL REFERENCES MESS_LOCATIONS(MESS_ID),
  USER_ID      NUMBER NOT NULL REFERENCES USERS(USER_ID),
  ACCESS_ROLE  VARCHAR2(30) NOT NULL,   -- SUPER_ADMIN | MESS_ADMIN
  STATUS       VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UX_MESS_USER UNIQUE (MESS_ID, USER_ID)
);
CREATE INDEX IX_MUA_USER ON MESS_USER_ACCESS(USER_ID);

