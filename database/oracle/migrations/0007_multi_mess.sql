-- ---------- 4. Add MESS_ID to mess-scoped tables ----------
-- Each block is idempotent: skips if column already exists.
DECLARE
  TYPE t IS TABLE OF VARCHAR2(60);
  tabs t := t(
    'MEMBERS','MEAL_REQUESTS','MEAL_ENTRIES','GUEST_MEALS',
    'BAZAR_EXPENSES','MONTHLY_BILLS','BILL_ALLOCATIONS','DEPOSITS','PAYMENTS',
    'OTHER_CHARGES','MONTHLY_ACCOUNTS','MEMBER_MONTHLY_SUMMARY','MONTHLY_CLOSINGS',
    'NOTIFICATIONS','UPLOADED_FILES','TELEGRAM_NOTIFICATIONS','AUDIT_LOGS',
    'CONVERSATIONS','POLLS','POLL_OPTIONS','POLL_VOTES','CHAT_MESSAGES',
    'CHAT_THEME_PREFS','USER_NOTIFICATION_PREFS','MESSAGES','MESSAGE_REACTIONS',
    'MESSAGE_RECEIPTS','MESSAGE_DELETED_FOR','CHAT_MUTES','MEAL_REMINDER_LOG'
  );
  tn VARCHAR2(60);
  cnt NUMBER;
BEGIN
  FOR i IN 1..tabs.COUNT LOOP
    tn := tabs(i);
    SELECT COUNT(*) INTO cnt FROM user_tab_columns
     WHERE table_name=tn AND column_name='MESS_ID';
    IF cnt = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE '||tn||' ADD (MESS_ID NUMBER)';
    END IF;
    EXECUTE IMMEDIATE 'UPDATE '||tn||' SET MESS_ID = (SELECT MESS_ID FROM MESS_LOCATIONS WHERE MESS_CODE=''ATTIC712'') WHERE MESS_ID IS NULL';
    EXECUTE IMMEDIATE 'UPDATE '||tn||' SET MESS_ID = 1 WHERE MESS_ID IS NULL';
    SELECT COUNT(*) INTO cnt FROM user_tab_columns
     WHERE table_name=tn AND column_name='MESS_ID' AND nullable='Y';
    IF cnt > 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE '||tn||' MODIFY (MESS_ID NUMBER DEFAULT 1 NOT NULL)';
    ELSE
      EXECUTE IMMEDIATE 'ALTER TABLE '||tn||' MODIFY (MESS_ID NUMBER DEFAULT 1)';
    END IF;
    SELECT COUNT(*) INTO cnt FROM user_indexes
     WHERE index_name='IXM_'||tn;
    IF cnt = 0 THEN
      EXECUTE IMMEDIATE 'CREATE INDEX IXM_'||tn||' ON '||tn||'(MESS_ID)';
    END IF;
  END LOOP;
END;
/

-- FK constraints to MESS_LOCATIONS (validated — all rows = mess 1)
DECLARE
  TYPE t IS TABLE OF VARCHAR2(60);
  tabs t := t(
    'MEMBERS','MEAL_REQUESTS','MEAL_ENTRIES','GUEST_MEALS',
    'BAZAR_EXPENSES','MONTHLY_BILLS','BILL_ALLOCATIONS','DEPOSITS','PAYMENTS',
    'OTHER_CHARGES','MONTHLY_ACCOUNTS','MEMBER_MONTHLY_SUMMARY','MONTHLY_CLOSINGS',
    'NOTIFICATIONS','UPLOADED_FILES','TELEGRAM_NOTIFICATIONS','AUDIT_LOGS',
    'CONVERSATIONS','POLLS','POLL_OPTIONS','POLL_VOTES','CHAT_MESSAGES',
    'CHAT_THEME_PREFS','USER_NOTIFICATION_PREFS','MESSAGES','MESSAGE_REACTIONS',
    'MESSAGE_RECEIPTS','MESSAGE_DELETED_FOR','CHAT_MUTES','MEAL_REMINDER_LOG'
  );
  tn VARCHAR2(60);
  cnt NUMBER;
BEGIN
  FOR i IN 1..tabs.COUNT LOOP
    tn := tabs(i);
    SELECT COUNT(*) INTO cnt FROM user_constraints
     WHERE table_name=tn AND constraint_name='FKM_'||tn;
    IF cnt = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE '||tn||' ADD CONSTRAINT FKM_'||tn||' FOREIGN KEY (MESS_ID) REFERENCES MESS_LOCATIONS(MESS_ID)';
    END IF;
  END LOOP;
END;
/

-- ---------- 5. SYSTEM_SETTINGS: mess-scoped keys ----------
-- MESS_ID NULL = global; non-null = per-mess override.
DECLARE
  has_col NUMBER;
BEGIN
  SELECT COUNT(*) INTO has_col FROM user_tab_columns
   WHERE table_name='SYSTEM_SETTINGS' AND column_name='MESS_ID';
  IF has_col = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE SYSTEM_SETTINGS ADD (MESS_ID NUMBER)';
  END IF;
END;
/
