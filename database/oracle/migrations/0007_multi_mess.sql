-- ---------- 6. Grant existing ADMIN users access to Mess 1 ----------
INSERT INTO MESS_USER_ACCESS (MESS_ID, USER_ID, ACCESS_ROLE, STATUS)
SELECT 1, u.USER_ID, 'MESS_ADMIN', 'ACTIVE'
  FROM USERS u JOIN ROLES r ON r.ROLE_ID=u.ROLE_ID
 WHERE r.ROLE_NAME='ADMIN'
   AND NOT EXISTS (SELECT 1 FROM MESS_USER_ACCESS a WHERE a.MESS_ID=1 AND a.USER_ID=u.USER_ID);
-- SUPER_ADMIN gets global access record too (informational)
INSERT INTO MESS_USER_ACCESS (MESS_ID, USER_ID, ACCESS_ROLE, STATUS)
SELECT 1, u.USER_ID, 'SUPER_ADMIN', 'ACTIVE'
  FROM USERS u JOIN ROLES r ON r.ROLE_ID=u.ROLE_ID
 WHERE r.ROLE_NAME='SUPER_ADMIN'
   AND NOT EXISTS (SELECT 1 FROM MESS_USER_ACCESS a WHERE a.MESS_ID=1 AND a.USER_ID=u.USER_ID);

COMMIT;

