--------------------------------------------------------------------------------
-- Data migration: existing CHAT_MESSAGES -> GROUP conversation "Community Chat"
--------------------------------------------------------------------------------
DECLARE
  v_group NUMBER;
  v_min_user NUMBER;
BEGIN
  SELECT CONVERSATION_ID INTO v_group FROM CONVERSATIONS WHERE CONVERSATION_TYPE='GROUP' AND ROWNUM=1;
EXCEPTION WHEN NO_DATA_FOUND THEN
  SELECT MIN(USER_ID) INTO v_min_user FROM USERS;
  INSERT INTO CONVERSATIONS (CONVERSATION_TYPE, TITLE, CREATED_BY)
    VALUES ('GROUP','Community Chat', v_min_user) RETURNING CONVERSATION_ID INTO v_group;
END;
/

-- copy history once (guard: only if MESSAGES empty for this conversation)
DECLARE
  v_group NUMBER;
BEGIN
  SELECT CONVERSATION_ID INTO v_group FROM CONVERSATIONS WHERE CONVERSATION_TYPE='GROUP' AND ROWNUM=1;
  INSERT INTO MESSAGES (CONVERSATION_ID, SENDER_ID, BODY, FILE_ID, FILE_NAME, FILE_MIME, CREATED_AT)
  SELECT v_group, c.SENDER_ID, c.BODY, c.IMAGE_FILE_ID,
         f.ORIGINAL_NAME, f.MIME_TYPE, c.CREATED_AT
  FROM CHAT_MESSAGES c
  LEFT JOIN UPLOADED_FILES f ON f.FILE_ID = c.IMAGE_FILE_ID
  WHERE NOT EXISTS (SELECT 1 FROM MESSAGES m WHERE m.CONVERSATION_ID = v_group);
END;
/

