-- 0004: chat themes + conversation mutes (per-user)
DECLARE
  v NUMBER;
BEGIN
  SELECT COUNT(*) INTO v FROM user_tables WHERE table_name='CHAT_THEME_PREFS';
  IF v=0 THEN EXECUTE IMMEDIATE q'[CREATE TABLE CHAT_THEME_PREFS (
    USER_ID NUMBER NOT NULL PRIMARY KEY,
    THEME_KEY VARCHAR2(40) DEFAULT 'whatsapp',
    CUSTOM_JSON CLOB,
    CONV_OVERRIDES CLOB,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
  )]'; END IF;

  SELECT COUNT(*) INTO v FROM user_tables WHERE table_name='CHAT_MUTES';
  IF v=0 THEN EXECUTE IMMEDIATE q'[CREATE TABLE CHAT_MUTES (
    USER_ID NUMBER NOT NULL,
    CONVERSATION_ID NUMBER NOT NULL,
    MUTED NUMBER(1) DEFAULT 1,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    PRIMARY KEY (USER_ID, CONVERSATION_ID)
  )]'; END IF;

  EXECUTE IMMEDIATE q'[CREATE INDEX IDX_CHAT_MUTES_CONV ON CHAT_MUTES(CONVERSATION_ID)]';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
EXIT;
